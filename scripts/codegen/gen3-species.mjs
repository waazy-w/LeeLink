// Generates the Gen 3 internal species index -> national dex table from a pret decomp checkout.
// usage: node scripts/codegen/gen3-species.mjs <path/to/pokefirered>
import { readFileSync, writeFileSync } from 'node:fs';
const root = process.argv[2];
const speciesH = readFileSync(`${root}/include/constants/species.h`, 'utf8');
const dexH = readFileSync(`${root}/include/constants/pokedex.h`, 'utf8');
const internal = {};
for (const [, name, n] of speciesH.matchAll(/#define SPECIES_(\w+) (\d+)\b/g)) internal[name] = +n;
const nationalNames = [...dexH.matchAll(/NATIONAL_DEX_(\w+),/g)].map((m) => m[1]);
const national = Object.fromEntries(nationalNames.map((n, i) => [n, i])); // NONE = 0
const table = [];
for (const [name, idx] of Object.entries(internal)) {
  if (idx === 0 || name === 'EGG' || name.startsWith('OLD_UNOWN')) continue;
  if (national[name] !== undefined) table[idx] = national[name];
}
const max = Math.max(...Object.values(internal).filter((n) => n < 500));
const out = Array.from({ length: max + 1 }, (_, i) => table[i] ?? 0);
writeFileSync(new URL('../../packages/shared/src/gen3/species-index.ts', import.meta.url),
`// GENERATED by scripts/codegen/gen3-species.mjs from pret/pokefirered. Do not edit.
// Gen 3 internal species index -> national dex number (0 = none / placeholder).
export const GEN3_INTERNAL_TO_NATIONAL: readonly number[] = ${JSON.stringify(out)};
export const GEN3_SPECIES_EGG = ${internal.EGG};
`);
console.log('mapped', out.filter(Boolean).length, 'max index', max, 'treecko', out[internal.TREECKO], 'chimecho', out[internal.CHIMECHO]);
