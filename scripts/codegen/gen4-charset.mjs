// Generates the Gen 4 (DPPt/HGSS) 16-bit text decoding table from pret/pokeplatinum's
// tools/msgenc/charmap.txt. Covers the Japanese + international range 0x0000-0x01FF; Korean
// (0x0400+) is left out because Korean ROMs aren't supported by the profiles.
// usage: node scripts/codegen/gen4-charset.mjs <pokeplatinum>/tools/msgenc/charmap.txt
import { readFileSync, writeFileSync } from 'node:fs';
const table = Array(0x200).fill('');
for (const line of readFileSync(process.argv[2], 'utf8').split('\n')) {
  const m = line.match(/^([0-9A-F]{4})=(.*)$/);
  if (!m) continue;
  const code = parseInt(m[1], 16);
  if (code >= table.length || m[2].startsWith('{') || m[2].startsWith('\\x')) continue;
  table[code] = m[2];
}
// 0x01DE and 0x01E2 are the (narrow) space glyphs; 0x0001 is the full-width space.
table[0x01de] = ' ';
table[0x01e2] = ' ';
writeFileSync(new URL('../../packages/shared/src/gen4/charset-table.ts', import.meta.url),
`// GENERATED by scripts/codegen/gen4-charset.mjs from pret/pokeplatinum tools/msgenc/charmap.txt. Do not edit.
// Index = Gen 4 character code (0x0000-0x01FF), value = Unicode text ('' = unmapped/control).
export const GEN4_CHARSET: readonly string[] = ${JSON.stringify(table)};
`);
console.log(table.slice(0x12b, 0x1bd).join(''));
