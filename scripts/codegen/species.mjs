// Generates packages/shared/src/data/species.ts and moves.ts from PokeAPI CSVs (Gen 1-5 only).
// usage: node scripts/codegen/species.mjs <dir-with-pokeapi-csvs>
import { readFileSync, writeFileSync } from 'node:fs';
const dir = process.argv[2];
const MAX = 649;
const csv = (f) => {
  const [head, ...rows] = readFileSync(`${dir}/${f}.csv`, 'utf8').trim().split('\n');
  const keys = head.split(',');
  return rows.map((r) => {
    const cells = r.match(/("([^"]|"")*"|[^,]*)(,|$)/g).map((c) => c.replace(/,$/, '').replace(/^"|"$/g, ''));
    return Object.fromEntries(keys.map((k, i) => [k, cells[i]]));
  });
};
const typeName = Object.fromEntries(csv('types').map((t) => [t.id, t.identifier]));
const names = {};
for (const n of csv('pokemon_species_names')) if (n.local_language_id === '9') names[n.pokemon_species_id] = n.name;
const types = {};
for (const t of csv('pokemon_types')) if (+t.pokemon_id <= MAX) (types[t.pokemon_id] ??= [])[+t.slot - 1] = typeName[t.type_id];
// past types: generation_id = last generation the old typing applied
const past = {};
for (const t of csv('pokemon_types_past')) if (+t.pokemon_id <= MAX) ((past[t.pokemon_id] ??= {})[t.generation_id] ??= [])[+t.slot - 1] = typeName[t.type_id];
const species = csv('pokemon_species').filter((s) => +s.id <= MAX).sort((a, b) => a.id - b.id);
const rows = species.map((s) => {
  const id = +s.id;
  const entry = {
    id, name: names[id], gen: +s.generation_id, family: +s.evolution_chain_id,
    from: s.evolves_from_species_id ? +s.evolves_from_species_id : 0,
    types: types[id].filter(Boolean), growth: +s.growth_rate_id, catchRate: +s.capture_rate,
  };
  if (past[id]) entry.pastTypes = Object.fromEntries(Object.entries(past[id]).map(([g, t]) => [g, t.filter(Boolean)]));
  return entry;
});
writeFileSync(new URL('../../packages/shared/src/data/species-table.ts', import.meta.url),
`// GENERATED by scripts/codegen/species.mjs from PokeAPI data. Do not edit.
import type { SpeciesInfo } from './species';
export const SPECIES_TABLE: readonly SpeciesInfo[] = ${JSON.stringify(rows)};
`);
const moveNames = {};
for (const n of csv('move_names')) if (n.local_language_id === '9') moveNames[n.move_id] = n.name;
const moves = csv('moves').filter((m) => +m.generation_id <= 5 && +m.id <= 559).sort((a, b) => a.id - b.id);
const moveArr = [''];
for (const m of moves) moveArr[+m.id] = moveNames[m.id];
writeFileSync(new URL('../../packages/shared/src/data/move-names.ts', import.meta.url),
`// GENERATED by scripts/codegen/species.mjs from PokeAPI data. Do not edit.
export const MOVE_NAMES: readonly string[] = ${JSON.stringify(moveArr)};
`);
console.log('species', rows.length, 'moves', moveArr.length - 1);
