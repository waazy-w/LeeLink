// Generates the Gen 3 (western) text decoding table from a pret decomp's charmap.txt.
// usage: node scripts/codegen/gen3-charset.mjs <path/to/charmap.txt>
import { readFileSync, writeFileSync } from 'node:fs';
const table = Array(256).fill('');
for (const line of readFileSync(process.argv[2], 'utf8').split('\n')) {
  const m = line.match(/^'(\\?.|[^']+)'\s*=\s*([0-9A-F]{2})\s*$/);
  if (!m) continue;
  const code = parseInt(m[2], 16);
  const ch = m[1] === "\\'" ? "'" : m[1];
  if (!table[code]) table[code] = ch;
}
table[0x00] = ' ';
writeFileSync(new URL('../../packages/shared/src/gen3/charset-table.ts', import.meta.url),
`// GENERATED by scripts/codegen/gen3-charset.mjs from pret charmap.txt. Do not edit.
export const GEN3_CHARSET: readonly string[] = ${JSON.stringify(table)};
`);
